const root = document.documentElement;
const langButton = document.querySelector(".lang-switch");
const menuButton = document.querySelector(".menu-toggle");
const mobileNav = document.querySelector(".mobile-nav");
const dialog = document.querySelector(".image-dialog");
const dialogImage = dialog.querySelector("img");
const closeDialog = dialog.querySelector(".dialog-close");
let language = localStorage.getItem("portfolio-language") || "en";

function setLanguage(nextLanguage) {
  language = nextLanguage;
  const isArabic = language === "ar";
  root.lang = language;
  root.dir = isArabic ? "rtl" : "ltr";
  document.querySelectorAll("[data-copy]").forEach((element) => {
    const key = element.dataset.copy;
    if (copy[language][key]) element.innerHTML = copy[language][key];
  });
  langButton.textContent = isArabic ? "English" : "عربي";
  langButton.setAttribute("aria-label", isArabic ? "Switch to English" : "التبديل إلى العربية");
  localStorage.setItem("portfolio-language", language);
}

langButton.addEventListener("click", () => setLanguage(language === "en" ? "ar" : "en"));
setLanguage(language);

menuButton.addEventListener("click", () => {
  const isOpen = mobileNav.classList.toggle("is-open");
  menuButton.setAttribute("aria-expanded", String(isOpen));
  menuButton.setAttribute("aria-label", isOpen ? "Close menu" : "Open menu");
});
mobileNav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  mobileNav.classList.remove("is-open");
  menuButton.setAttribute("aria-expanded", "false");
}));

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.1 });
document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

document.querySelectorAll(".project-image").forEach((button) => {
  button.addEventListener("click", () => {
    dialogImage.src = button.dataset.image;
    dialogImage.alt = button.dataset.alt;
    dialog.showModal();
  });
});
closeDialog.addEventListener("click", () => dialog.close());
dialog.addEventListener("click", (event) => {
  if (event.target === dialog) dialog.close();
});

document.querySelector("#year").textContent = new Date().getFullYear();
